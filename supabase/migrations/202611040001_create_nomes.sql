create table if not exists public.nomes (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) between 1 and 120),
  created_at timestamptz not null default now()
);

alter table public.nomes enable row level security;

-- A aplicação de demonstração permite somente inserções públicas.
-- Leitura, atualização e exclusão permanecem bloqueadas para usuários anon.
drop policy if exists "Permitir inserir nomes pela aplicação de teste" on public.nomes;

create policy "Permitir inserir nomes pela aplicação de teste"
on public.nomes
for insert
to anon
with check (char_length(trim(nome)) between 1 and 120);
